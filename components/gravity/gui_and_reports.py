    def _inputs(self):
        model = Path(self.model_var.get()).expanduser().resolve()
        report_path = model.parent / 'OpenSees_Complete_Export_Report_V118.json'
        if model.name.startswith('OpenSees_Complete_') and report_path.is_file():
            errors = json.loads(report_path.read_text(encoding='utf-8-sig')).get('assembly_errors', [])
            if errors: raise ValueError('Model assembly blocked: ' + '; '.join(errors) + '. Rebuild with the latest exporter. Manual support inputs cannot repair assembly.')
        out = Path(self.output_var.get()).expanduser().resolve()
        py = Path(self.python_var.get()).expanduser().resolve()
        if not model.is_file(): raise ValueError("Select an existing generated OpenSees model script.")
        if not py.is_file(): raise ValueError("Select a valid Python executable with OpenSeesPy installed.")
        if not out.exists(): out.mkdir(parents=True, exist_ok=True)
        try:
            supports = [int(x.strip()) for x in self.support_var.get().replace(";", ",").split(",") if x.strip()]
            total = float(self.load_var.get()); steps = int(self.steps_var.get())
        except ValueError as exc: raise ValueError("Enter comma-separated integer support tags, a numeric load in kN, and an integer step count.") from exc
        if not supports or total <= 0 or steps < 1: raise ValueError("Support tags, positive applied load and at least one load step are required.")
        if len(set(supports)) != len(supports): raise ValueError("Support node tags contain duplicates; each support must appear once.")
        return model, out, py, supports, total, steps

    def run(self):
        try: model, out, py, supports, total, steps = self._inputs()
        except Exception as exc:
            messagebox.showerror("Gravity inputs need review", str(exc), parent=self.win); return
        if not self.coverage_confirmed.get():
            messagebox.showerror("Gravity load coverage not confirmed", "Review the generated model and verify the total downward load against the project load ledger. The code-derived line-load total may omit slab, wall, self-weight, FVD/BRB or other loads. Confirm coverage before running.", parent=self.win); return
        self.run_button.configure(state="disabled")
        self.status_var.set("Running model and nonlinear gravity steps…")
        self.log.delete("1.0", "end")
        self.log.insert("end", f"Model: {model}\nOutput folder: {out}\nSupports: {supports}\nApplied load: {total:g} kN\nSteps: {steps}\n")
        self.win.update_idletasks()
        result_path = out / "Gravity_Result_V110.json"
        runner_path = out / "Gravity_Run_V110.py"
        log_path = out / "Gravity_Run_V110.log"
        runner_path.write_text(_runner_source(model, result_path, supports, total, steps), encoding="utf-8")
        thread = threading.Thread(target=self._worker, args=(py, runner_path, result_path, log_path, out), daemon=True)
        thread.start()

    def _worker(self, py, runner, result_path, log_path, out):
        try:
            proc = subprocess.run([str(py), str(runner)], cwd=str(out), capture_output=True, text=True, errors="replace", env={**dict(__import__('os').environ),'PYTHONIOENCODING':'utf-8','PYTHONUTF8':'1'}, encoding='utf-8')
            combined = proc.stdout + ("\n--- STDERR ---\n" + proc.stderr if proc.stderr else "")
            log_path.write_text(combined, encoding="utf-8")
            if not result_path.exists():
                payload = {"ok": False, "error": f"Runner exited {proc.returncode} without a result JSON."}
            else:
                payload = json.loads(result_path.read_text(encoding="utf-8"))
            if proc.returncode != 0: payload["ok"] = False
            self.win.after(0, lambda: self._finished(payload, combined, out))
        except Exception as exc:
            detail = traceback.format_exc()
            try: log_path.write_text(detail, encoding="utf-8")
            except Exception: pass
            self.win.after(0, lambda: self._finished({"ok": False, "error": str(exc)}, detail, out))

    def _finished(self, payload, log_text, out):
        self.run_button.configure(state="normal")
        self.log.insert("end", "\n" + log_text + "\n")
        self.log.see("end")
        if not payload.get("ok"):
            self.status_var.set("Gravity run failed — see the log for the failing step.")
            messagebox.showerror("Gravity analysis failed", payload.get("error", "Unknown error"), parent=self.win)
            self.nb.select(self.log_tab)
            return
        try:
            paths = self._make_outputs(payload, out)
        except Exception as exc:
            self.status_var.set("Analysis passed; report generation failed.")
            messagebox.showerror("Report generation failed", str(exc), parent=self.win)
            self.nb.select(self.log_tab)
            return
        rep = payload["report"]
        self.status_var.set(f"Gravity PASS | equilibrium error {rep['equilibrium_error_percent']:.4g}% | {rep['elapsed_seconds']:.2f} s | outputs saved in {out}")
        self.nb.select(self.plot_tab)
        messagebox.showinfo("Gravity analysis complete", "Gravity converged; reaction check passed; gravity frozen at time zero.\n\nExcel workbook, separate 300 dpi PNG/PDF figures and critical-action PDF saved.\nUse the result tabs or Open output folder to inspect them.\n\n" + str(out), parent=self.win)

